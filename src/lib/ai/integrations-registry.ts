/**
 * Scans user prompts & replies to suggest relevant ChatGPT-style In-Chat Plugin Cards
 * ONLY for integrations mentioned/needed that are NOT yet connected.
 */
export function detectIntegrationsMentionedInText(
  text: string,
  connectedIds: string[] = []
): IntegrationCatalogEntry[] {
  const lower = text.toLowerCase();
  const matches: IntegrationCatalogEntry[] = [];
  const connectedSet = new Set(connectedIds);

  for (const item of UNIVERSAL_INTEGRATIONS_CATALOG) {
    if (connectedSet.has(item.id)) continue;
    const hit = item.keywords.some((kw) => {
      const k = kw.toLowerCase();
      if (k.length <= 2) {
        return new RegExp(`\\b${k}\\b`, "i").test(lower);
      }
      return lower.includes(k);
    });
    if (hit) {
      matches.push(item);
    }
    if (matches.length >= 4) break;
  }

  return matches;
}
